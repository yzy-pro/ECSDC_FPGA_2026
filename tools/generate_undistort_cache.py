"""Generate/check eight-band tables for the confirmed 1920 calibration."""
import argparse
import json
import math
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
WARP_MARGIN=4
ROWS=(58,56,26,18,18,28,68,58)
BASES=tuple(sum(ROWS[:b])*15//2 for b in range(8))
CACHE_DEPTH=sum(ROWS)*15//2
SLOT_BITS=6
FX,FY,CX,CY=748.4469,748.0773,944.9033,522.3963
FX_Q14,FY_Q14,CX_Q14,CY_Q14=12262554,12256498,15481296,8558941
XN_START,YN_START,XN_STEP,YN_STEP=-5289644,-2923354,5604,5607

def literal(v):
    return ('-' if v<0 else '')+"18'sd"+str(abs(v))

def coefficient(text,name):
    m=re.search(r'\b'+name+r"\s*=\s*(-?)18'sd(\d+)",text)
    if not m: raise ValueError('Missing coefficient '+name)
    return int(m[2])*(-1 if m[1] else 1)

def mapping(x,y,p1=0,p2=0):
    r2=(x*x+y*y)>>14
    r4=r2*r2>>14
    scale=16384+((162*r2)>>14)+((-711*r4)>>14)
    xx,yy,xy=x*x>>14,y*y>>14,x*y>>14
    tx=((p1*xy)>>13)+((p2*(r2+2*xx))>>14)
    ty=((p1*(r2+2*yy))>>14)+((p2*xy)>>13)
    xd,yd=((x*scale)>>14)+tx,((y*scale)>>14)+ty
    if not all(-131072<=v<=131071 for v in (r2,r4,scale,tx,ty,xd,yd)):
        raise ValueError('Q14 overflow')
    return ((xd*FX_Q14)>>14)+CX_Q14,((yd*FY_Q14)>>14)+CY_Q14

def schedule(p1=0,p2=0):
    if p1 or p2: raise ValueError('Approved tables require p1=p2=0')
    rows=[]
    xs=[(XN_START+x*XN_STEP)>>8 for x in range(1920)]
    for row in range(1080):
        y=(YN_START+row*YN_STEP)>>8
        yf=(row+1-CY)/FY
        bounds=[[1080,-1] for _ in range(8)]
        for col,x in enumerate(xs):
            u,v=mapping(x,y)
            xf=(col+1-CX)/FX
            r=xf*xf+yf*yf
            s=1+.0099*r-.0434*r*r
            uf,vf=FX*xf*s+CX,FY*yf*s+CY
            ix,iy=math.floor(uf),math.floor(vf)
            points=[((u>>14)-1,(v>>14)-1),(ix-1,iy-1),
                    (ix-1+(math.floor((uf-ix)*32+.5)==32),
                     iy-1+(math.floor((vf-iy)*32+.5)==32))]
            for sx,sy in points:
                if not(0<=sx<1919 and 0<=sy<1079):
                    raise ValueError('Unsupported calibration boundary clamp')
                # Cover every bounded dynamic affine displacement, including
                # crossings into the adjacent source-x strip and both taps.
                for b in range(max(0,sx-WARP_MARGIN)//240,
                               min(1919,sx+WARP_MARGIN)//240+1):
                    bounds[b][0]=min(bounds[b][0],max(0,sy-WARP_MARGIN))
                    bounds[b][1]=max(bounds[b][1],min(1079,sy+1+WARP_MARGIN))
        rows.append(bounds)
    for b,capacity in enumerate(ROWS):
        for row,bounds in enumerate(rows):
            lo,hi=bounds[b]
            if not(0<=lo<=hi<1080) or hi-lo+1>capacity-4:
                raise ValueError(f'band {b} row {row} capacity exceeded')
            if row and any(a>c for a,c in zip(rows[row-1][b],bounds[b])):
                raise ValueError('Nonmonotonic band window')
            # Retain the previous row too: its last pixels may still be in
            # the pixel pipeline when DDR observes the falling DE edge.
            if rows[min(row+2,1079)][b][1]-rows[max(row-1,0)][b][0]+1>capacity:
                raise ValueError('Lookahead overwrites live slot')
    return rows

def packed(values,width):
    return sum(v<<(width*i) for i,v in enumerate(values))

def table_source(rows):
    first=packed([b[0] for b in rows[0]],11)
    entries='\n'.join(f"        limits[{i}] = 88'h{packed([b[1] for b in r],11):022x};" for i,r in enumerate(rows))
    slots='\n'.join(f"        slots[{y}] = 48'h{packed([y%(n//2) for n in ROWS],SLOT_BITS):012x};" for y in range(541))
    return f"""// Generated by tools/generate_undistort_cache.py. Do not hand-edit.
// k1=0.0099 k2=-0.0434; 1920x1080; p1=p2=0.
// Dynamic source-coordinate envelope +/-{WARP_MARGIN} pixels in x/y.
module undistort_band_schedule(input clk, input [10:0] row,
    output [87:0] first_rows,
    output reg [87:0] current_max, output reg [87:0] future_max);
    assign first_rows = 88'h{first:022x};
    reg [87:0] limits [0:1079];
    initial begin
{entries}
    end
    wire [10:0] ahead = (row < 1078) ? row + 11'd2 : 11'd1079;
    always @(posedge clk) begin
        current_max <= (row < 1080) ? limits[row] : 88'd0;
        future_max <= limits[ahead];
    end
endmodule

module undistort_band_slots(input clk, input [9:0] half_y,
    output reg [47:0] slot_rows);
    reg [47:0] slots [0:540];
    initial begin
{slots}
    end
    always @(posedge clk) slot_rows <= (half_y < 541) ? slots[half_y] : 48'd0;
endmodule
"""

def check_parameters(root):
    c=json.loads((root/'calibration/camera_20260930.json').read_text(encoding='utf-8'))
    if (c['intrinsic_matrix_matlab']!=[[FX,0,0],[0,FY,0],[CX,CY,1]] or
        c['radial_distortion']!=[.0099,-.0434] or c['tangential_distortion']!=[0,0] or
        c['image_size_hw']!=[1080,1920]):
        raise ValueError('Input calibration differs from approved arithmetic')
    rtl=(root/'src/video/undistort_rd_buf.v').read_text(encoding='ascii')
    for name,value in dict(FX_Q14=FX_Q14,FY_Q14=FY_Q14,CX_Q14=CX_Q14,CY_Q14=CY_Q14,
        K1_Q14=162,K2_Q14=-711,XN_START_Q22=XN_START,YN_START_Q22=YN_START,
        XN_STEP_Q22=XN_STEP,YN_STEP_Q22=YN_STEP).items():
        m=re.search(r'\b'+name+r"\s*=\s*(-?)\d+'sd(\d+)",rtl)
        if not m or int(m[2])*(-1 if m[1] else 1)!=value:
            raise ValueError('RTL calibration mismatch: '+name)
    for file,names in [('src/hdmi_ddr3_top.v',('DIST_P1_Q14','DIST_P2_Q14')),
        ('src/video/fram_buf_undistort.v',('P1_Q14','P2_Q14')),
        ('src/video/undistort_rd_buf.v',('P1_Q14','P2_Q14'))]:
        text=(root/file).read_text(encoding='ascii')
        if any(coefficient(text,n) for n in names): raise ValueError('Tangential table mismatch')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',type=Path,default=ROOT)
    p.add_argument('--write',action='store_true')
    a=p.parse_args()
    check_parameters(a.root)
    rows=schedule()
    expected=table_source(rows)
    path=a.root/'src/video/undistort_band_tables.v'
    if a.write: path.write_text(expected,encoding='ascii')
    elif not path.is_file() or path.read_text(encoding='ascii')!=expected:
        raise SystemExit('Band ROMs missing/stale: regenerate with --write')
    print(f'PASS eight-band tables: 2073600 pixels, {CACHE_DEPTH} words/parity, +/-{WARP_MARGIN}px dynamic envelope, two-line lookahead')

if __name__=='__main__': main()
